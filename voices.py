"""
Voices and sound effects for the meme editor.

VOICES: every chat message is spoken out loud with the Mac's built-in voices
(the `say` command, free and offline). Each color always gets the same voice
and pitch, so "Red" always sounds like Red. Chat slang is cleaned up first
("u" -> "you", "wh?" -> "what?").

To pick voices yourself, edit COLOR_VOICES below. See all voices on your Mac:
  say -v '?'

SOUND EFFECTS: pop (a message appears), boom (a meme), whoosh ("a few moments
earlier"), sting (the reveal). They're generated by code. To use your own
sounds instead, put files named pop / boom / whoosh / sting (.wav or .mp3)
in storage/sfx/.

Try it:  python voices.py "where?? i sus blue"
"""

import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent
SFX_DIR = BASE / "storage" / "sfx"
CACHE = BASE / "storage" / "voice_cache"

# Your own choices go here, e.g. "red": ("Fred", 1.15). (voice name, pitch)
COLOR_VOICES = {}

# Voices to pick from automatically (the first ones your Mac has are used)
VOICE_POOL = ["Fred", "Junior", "Ralph", "Kathy", "Albert", "Samantha", "Daniel",
              "Karen", "Moira", "Rishi", "Tessa", "Zarvox", "Trinoids", "Whisper",
              "Superstar", "Bubbles", "Eddy (English (US))", "Flo (English (US))",
              "Reed (English (US))", "Rocko (English (US))", "Sandy (English (US))",
              "Shelley (English (US))", "Grandpa (English (US))", "Grandma (English (US))"]
ME_VOICE = ("Samantha", 1.0)
PITCHES = [1.0, 1.12, 0.9, 1.22, 0.95, 1.08, 1.3, 0.85]
SPEED = 185  # words per minute

SLANG = {
    "u": "you", "r": "are", "ur": "your", "pls": "please", "plz": "please",
    "idk": "I don't know", "wh": "what", "ya": "yeah", "yea": "yeah", "y": "why",
    "eng": "engineer", "enginee": "engineer", "imp": "impostor", "imposter": "impostor",
    "sus": "suss", "lol": "L O L", "lmao": "L M A O", "bruh": "bruh", "k": "okay",
    "tf": "the heck", "wtf": "what the heck", "rn": "right now", "dc": "disconnected",
    "afk": "A F K", "gg": "G G", "cams": "cameras", "elec": "electrical",
    "nav": "navigation", "med": "med bay", "o2": "oxygen",
}


# ---------- helpers ----------

def _run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr.strip()[-400:])
    return r.stdout


def duration(path):
    out = _run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                "-of", "csv=p=0", str(path)])
    try:
        return float(out.strip())
    except ValueError:
        return 0.0


def speakable(text):
    """Turn chat text into something a voice can say."""
    text = str(text or "").strip()
    text = re.sub(r"\bwh\?", "what?", text, flags=re.I)
    words = []
    for w in text.split():
        m = re.match(r"^(\W*)([\w']+)(\W*)$", w)
        if m and m.group(2).lower() in SLANG:
            w = m.group(1) + SLANG[m.group(2).lower()] + m.group(3)
        words.append(w)
    out = " ".join(words)
    out = re.sub(r"([!?.])\1+", r"\1", out)  # "where??" -> "where?"
    return out or "..."


_mac_voices = None


def mac_voices():
    global _mac_voices
    if _mac_voices is None:
        _mac_voices = []
        if shutil.which("say"):
            out = subprocess.run(["say", "-v", "?"], capture_output=True, text=True).stdout
            for line in out.splitlines():
                m = re.match(r"^(.+?)\s{2,}[a-z]{2}[_-][A-Z]{2}", line)
                if m:
                    _mac_voices.append(m.group(1).strip())
    return _mac_voices


def voice_for(color, is_me=False):
    """(voice name, pitch) for a color. Same color = same voice every time."""
    if is_me:
        return COLOR_VOICES.get("me", ME_VOICE)
    if color in COLOR_VOICES:
        return COLOR_VOICES[color]
    have = [v for v in VOICE_POOL if v in mac_voices()] or mac_voices() or ["default"]
    h = int(hashlib.md5(str(color).encode()).hexdigest(), 16)
    return have[h % len(have)], PITCHES[(h // 7) % len(PITCHES)]


# ---------- speaking ----------

def speak(text, color, out_wav, is_me=False):
    """Say text in this color's voice. Saves a wav, returns its length (s)."""
    out_wav = Path(out_wav)
    voice, pitch = voice_for(color, is_me)
    line = speakable(text)
    CACHE.mkdir(parents=True, exist_ok=True)
    raw = CACHE / (hashlib.md5(f"{voice}|{line}".encode()).hexdigest() + ".aiff")

    if not raw.exists():
        if shutil.which("say"):
            cmd = ["say", "-r", str(SPEED), "-o", str(raw)]
            if voice != "default":
                cmd[1:1] = ["-v", voice]
            _run(cmd + [line])
        elif shutil.which("espeak-ng") or shutil.which("espeak"):
            eng = shutil.which("espeak-ng") or shutil.which("espeak")
            _run([eng, "-s", "165", "-w", str(raw.with_suffix(".wav")), line])
            raw = raw.with_suffix(".wav")
        else:
            # No speech engine (not a Mac): a short placeholder tone instead
            secs = max(0.4, 0.07 * len(line))
            _run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i",
                  f"sine=frequency=520:duration={secs:.2f}", "-af", "volume=0.15",
                  str(raw.with_suffix(".wav"))])
            raw = raw.with_suffix(".wav")

    # Pitch up/down without changing speed, then clean format
    af = (f"asetrate=44100*{pitch},aresample=44100,atempo={1 / pitch:.4f},"
          "silenceremove=start_periods=1:start_threshold=-50dB,"
          "areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,"
          "volume=1.6")
    _run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(raw), "-af", af,
          "-ar", "44100", "-ac", "2", str(out_wav)])
    return duration(out_wav)


# ---------- sound effects ----------

SYNTH = {
    # a short bubbly pop when a message appears
    "pop": ("aevalsrc='0.5*sin(2*PI*(500+900*exp(-30*t))*t)*exp(-28*t)':d=0.15", ""),
    # a deep boom for meme cards
    "boom": ("aevalsrc='0.9*sin(2*PI*(48+110*exp(-9*t))*t)*exp(-2.8*t)"
             "+0.25*(random(0)-0.5)*exp(-18*t)':d=1.2", "lowpass=f=400,volume=2.2"),
    # an airy whoosh for "a few moments earlier"
    "whoosh": ("anoisesrc=d=0.8:c=pink:a=0.6",
               "bandpass=f=1200:w=900,afade=t=in:d=0.35,afade=t=out:st=0.35:d=0.45"),
    # a dramatic two-hit sting for the reveal
    "sting": ("aevalsrc='0.5*(sin(2*PI*110*t)+sin(2*PI*164.8*t)+sin(2*PI*220*t))"
              "*exp(-1.6*t)':d=1.8", "volume=1.2"),
}


def sfx(name, work_dir):
    """Path to a sound effect: yours from storage/sfx/ if present, else generated."""
    for ext in (".wav", ".mp3", ".m4a", ".aiff"):
        mine = SFX_DIR / f"{name}{ext}"
        if mine.exists():
            return mine
    out = Path(work_dir) / f"sfx_{name}.wav"
    if not out.exists():
        src, af = SYNTH[name]
        cmd = ["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", src]
        if af:
            cmd += ["-af", af]
        _run(cmd + ["-ar", "44100", "-ac", "2", str(out)])
    return out


if __name__ == "__main__":
    text = " ".join(sys.argv[1:]) or "where?? i sus blue"
    print(f"Spoken as: {speakable(text)}")
    print(f"Voices found on this computer: {len(mac_voices())}")
    for color in ("red", "blue", "maroon", None):
        v, p = voice_for(color, is_me=color is None)
        out = BASE / "storage" / f"voice_test_{color or 'me'}.wav"
        out.parent.mkdir(parents=True, exist_ok=True)
        secs = speak(text, color, out, is_me=color is None)
        print(f"  {color or 'me':<7} -> {v} (pitch {p}), {secs:.1f}s  {out.name}")
        if shutil.which("afplay"):
            subprocess.run(["afplay", str(out)])
